// UPDATE phase: generate an updated roadmap document and open a PR.

import { createClient } from './github.js';
import { validateIssueBody, validateRoadmap, sanitizeForPrompt, wrapPrompt, redactErrorForLog, ISSUE_REF_PATTERN_SOURCE } from './safety.js';

// Canonical home is safety.js (the security boundary); re-exported here for
// backwards compat with existing imports.
export { redactErrorForLog };

const FALLBACK_PR_BODY_TAIL = 'No assessment available — roadmap updated based on current observation data.';

// The roadmap sections the LLM may append new entries to. Shared by the prompt
// builder (which advertises them) and applyEditOps (which validates against
// them and recovers ops where the model put a section name in the action
// field). Exported for testing.
export const SECTION_NAMES = ['Implemented', 'Next Up', 'Future'];

// Build the roadmap PR body. Optionally include the LLM-generated assessment;
// the caller is expected to validate the resulting string via validateIssueBody
// before sending it to the GitHub API.
export function buildRoadmapPrBody(assessmentText) {
  const tail = assessmentText
    ? `### Assessment\n\n${assessmentText}`
    : FALLBACK_PR_BODY_TAIL;
  return [
    '## Roadmap Update',
    '',
    'This PR was generated by [Repo Butler](https://github.com/IsmaelMartinez/repo-butler).',
    '',
    tail,
  ].join('\n');
}

const ROADMAP_BRANCH_PREFIX = 'repo-butler/roadmap-update-';

// Read the roadmap as it exists on one ref. Returns { content, sha } or null
// when the file is absent there or the read fails — callers decide the
// fallback, because "no roadmap on this branch" and "GitHub said no" both mean
// "use the default-branch copy" but neither should abort the run. Exported for
// testing.
export async function readRoadmapFromRef(gh, owner, repo, roadmapPath, ref) {
  try {
    const f = await gh.request(`/repos/${owner}/${repo}/contents/${roadmapPath}`, { params: { ref } });
    if (!f?.content) return null;
    return { content: Buffer.from(f.content, 'base64').toString('utf8'), sha: f.sha };
  } catch {
    return null;
  }
}

// Find an open roadmap-update PR. Returns the first match or null. Exported
// for testing. Uses the paginate helper's default cap (500) — a stale roadmap
// PR could otherwise be hidden behind 100+ unrelated PRs in busy consumer
// repos and cause the dedup to silently miss.
export async function findOpenRoadmapPr(gh, owner, repo) {
  const open = await gh.paginate(`/repos/${owner}/${repo}/pulls`, {
    params: { state: 'open' },
  });
  return open.find(pr => pr.head?.ref?.startsWith(ROADMAP_BRANCH_PREFIX)) || null;
}

// Conservative ceiling for the assessment text inside the PR body. Leaves
// headroom under safety.js's MAX_BODY_LENGTH (8000) for surrounding header
// and footer. Long-but-benign assessments are truncated rather than dropped
// — distinguishes "too verbose" from "blocked content" so operators can tell
// the false-positive from a real injection in the logs.
const MAX_ASSESSMENT_LENGTH = 6000;

// Extract every `#NN` PR/issue reference token from markdown text — `(PR
// #84)`, `PR #176`, `PRs #23–#37`, `issue #211`, and bare `#202` all yield the
// matched `#NN` token. Excludes `#N` that is really a URL/path fragment anchor —
// `docs/decisions/009-foo.md#2-decision`, `https://host/path#3` — or a local
// markdown anchor target (`[jump](#123)`); GitHub would not autolink those as
// issue references either, and counting them mints bogus refs (compactRoadmap
// would write a fabricated `#2` into a summary, and applyEditOps' shippedRefs
// dedup could skip a legitimate append citing the real PR #2). Uses
// safety.js's ISSUE_REF_PATTERN_SOURCE (same pattern backs BARE_ISSUE_REF
// there) so the two call sites can't drift apart. A range's second ref
// (`#23–#37`) follows a dash, and a parenthesised or space-preceded ref
// follows a delimiter (` (`, not `](`), so all the reference forms above
// still match. Returns a Set so duplicates collapse and order doesn't matter.
// The `g`-flagged RegExp is compiled once at module scope and reused — safe
// here because String.prototype.match() ignores any prior lastIndex and
// resets it to 0 when done, unlike .exec()/.test(), which read and persist
// lastIndex across calls and would need a fresh instance per call.
const ISSUE_REF_REGEXP = new RegExp(ISSUE_REF_PATTERN_SOURCE, 'g');
function extractIssueRefs(text) {
  return new Set((text?.match(ISSUE_REF_REGEXP) || []));
}

// Extract every `docs/decisions/NNN-*.md` ADR reference from markdown text as
// `{ path, num }` pairs, in first-appearance order with duplicates collapsed.
// Matches the path whether it sits inside a markdown link
// (`[ADR-009](docs/decisions/009-….md)`) or appears bare in prose; any
// `#anchor` suffix is dropped with the rest of the link syntax. Strict by
// design: the digits must be the repo's zero-padded `NNN-` ADR filename
// prefix, so `7-…`, `1234-…`, date-prefixed files (`2026-05-28-….md`), and
// nested paths (`/` is excluded from the tail) never mint a bogus `ADR-NNN`
// label; and both quantifiers are bounded so matching stays linear on
// adversarial text — compactRoadmap runs over LLM-written prose that
// incorporates external repo data. Used by compactRoadmap so ADR pointers
// survive compaction.
function extractAdrRefs(text) {
  const refs = new Map();
  for (const m of (text || '').matchAll(/docs\/decisions\/(\d{3})-[\w.-]{0,200}\.md/g)) {
    if (!refs.has(m[0])) refs.set(m[0], m[1]);
  }
  return [...refs].map(([path, num]) => ({ path, num }));
}

// Collect every pointer worth carrying into a compacted summary: all markdown
// links `[text](target)` in first-appearance order, deduped by target with the
// author's link text preserved, followed by any bare `docs/decisions/NNN-*.md`
// paths promoted to `[ADR-NNN](path)` links via extractAdrRefs. A path
// referenced both bare and as a link target appears once — the markdown link
// wins, so its text (and any `#anchor` in its target) survives; targets are
// compared with the anchor stripped for exactly that dedup. Bare paths outside
// docs/decisions/ are not carried: an unlinked path is prose, not a pointer,
// and only the ADR convention is unambiguous enough to promote. Targets may
// contain one level of balanced parentheses (valid CommonMark, e.g. Wikipedia
// URLs); deeper nesting or an unbalanced paren ends the target. Every regex
// quantifier is bounded and the alternatives are first-character disjoint
// (linear on adversarial text, same rationale as extractAdrRefs), and every
// character class excludes whitespace or newlines, so each returned link
// renders on one line. Returns rendered `[text](target)` strings. PR
// #312/#315 reviews: compaction must not cost the section its key pointers
// (files, research notes, ADRs).
function extractSummaryLinks(text) {
  const links = new Map(); // target as written → rendered link
  for (const m of (text || '').matchAll(/(?<!!)\[([^\]\n]{1,200})\]\(((?:[^()\s]|\([^()\s]{0,200}\)){1,400})\)/g)) {
    if (!links.has(m[2])) links.set(m[2], `[${m[1]}](${m[2]})`);
  }
  const linkedPaths = new Set([...links.keys()].map(t => t.replace(/#.*$/, '')));
  for (const { path, num } of extractAdrRefs(text)) {
    if (!linkedPaths.has(path) && !links.has(path)) links.set(path, `[ADR-${num}](${path})`);
  }
  return [...links.values()];
}

// True when the two documents are identical apart from the "**Last Updated:**"
// date (or identical outright). Used by the refresh path: a long-open roadmap
// PR would otherwise receive a commit every tick whose entire diff is the date
// line, because the LLM re-emits the same ops until the PR merges. Exported
// for testing.
export function isDateOnlyChange(a, b) {
  const norm = t => (t || '').replace(
    /(\*\*Last Updated:\*\*)\s*\d{4}-\d{2}-\d{2}/,
    '$1 <date>',
  );
  return norm(a) === norm(b);
}

// Build a safety-validated PR body. If the assessment-bearing body fails
// validation (blocked URLs, @mentions, key patterns, length, etc.), fall back
// to the assessment-free body so the roadmap PR can still ship with safe text.
// Truncates over-long assessments first so verbose-but-benign output doesn't
// trigger the fallback path.
export function buildSafePrBody(assessmentText) {
  if (!assessmentText) {
    return { body: buildRoadmapPrBody(null), redacted: false, truncated: false, errors: [] };
  }

  const truncated = assessmentText.length > MAX_ASSESSMENT_LENGTH;
  const safeText = truncated ? assessmentText.slice(0, MAX_ASSESSMENT_LENGTH) : assessmentText;
  const withAssessment = buildRoadmapPrBody(safeText);

  const result = validateIssueBody(withAssessment);
  if (result.valid) return { body: withAssessment, redacted: false, truncated, errors: [] };

  return { body: buildRoadmapPrBody(null), redacted: true, truncated, errors: result.errors };
}

// Thin orchestration wrapper used by the index dispatcher. Stores the
// result on context for downstream phases / GITHUB_OUTPUT reporting.
export async function runUpdate(context) {
  const result = await update(context);
  context.updateResult = result;
  return result;
}

export async function update(context) {
  const { owner, repo, token, snapshot, assessment, provider, config, dryRun } = context;

  if (!provider) {
    console.log('No LLM provider configured — skipping UPDATE phase.');
    return null;
  }

  if (!snapshot) {
    console.log('No snapshot available — run OBSERVE first.');
    return null;
  }

  const roadmapPath = config.roadmap?.path || 'ROADMAP.md';

  // `context.gh` is a test seam, not a feature: nothing in the pipeline sets
  // it. This function is the only path that writes ROADMAP.md, and it had no
  // test at all — which is how the refresh baseline defect below survived four
  // ticks of silently discarding entries. A fake client is the only way to
  // exercise the refresh wiring rather than just the helpers it calls.
  const gh = context.gh || createClient(token);

  // Idempotency: the daily pipeline runs 4×/day. If a previous run's PR is
  // still open, refresh its branch with the latest output rather than open a
  // duplicate. PR #202 stayed open from 2026-05-08 → 2026-05-11 and silenced
  // 12 cron ticks of soak data because the old skip path returned early
  // before the LLM call. The LLM still runs every tick; a tick whose ops
  // produce no content change (or only a date delta vs the PR branch) skips
  // the push without touching the open PR.
  const existing = await findOpenRoadmapPr(gh, owner, repo);
  const isRefresh = !!existing;

  // The baseline every later step edits: the prompt's read-only context, the
  // document applyEditOps appends to, and the "did anything change?" compare.
  //
  // On a refresh it MUST be the open PR branch's copy, not the default
  // branch's. `snapshot.roadmap` is what OBSERVE read from the default branch,
  // so using it here rebuilt the document from main every tick and pushed that
  // over the PR — silently discarding the previous tick's entry. PR #353
  // recorded the damage precisely: four refreshes, each writing one correct
  // entry (#354, then #355, then #356, then #357/#358) and each replacing the
  // last, so a PR that should have listed four shipped capabilities listed
  // one. Entries are never re-offered either, because ASSESS computes
  // `new_merged_prs` against the previous snapshot, so a PR that was new last
  // tick is not new this tick. Lost meant lost.
  //
  // Fail-safe: an unreadable branch copy falls back to the snapshot, i.e. the
  // old behaviour, rather than aborting the run.
  let currentRoadmap = snapshot.roadmap?.content || '';
  let branchFileSha;
  if (isRefresh) {
    const onBranch = await readRoadmapFromRef(gh, owner, repo, roadmapPath, existing.head.ref);
    if (onBranch) {
      currentRoadmap = onBranch.content;
      branchFileSha = onBranch.sha;
    } else {
      console.warn(`SECTION-EDIT: could not read ${roadmapPath} from ${existing.head.ref}; falling back to the default-branch copy.`);
    }
  }

  const today = new Date().toISOString().slice(0, 10);

  // Deterministic compaction before the LLM: trim the verbose bodies of
  // long-completed ~~SHIPPED~~ subsections so the live roadmap stays well under
  // the length ceiling (git history keeps the full prose). Running it first
  // makes the compacted document the baseline the prompt, applied ops, and
  // validation all see. The section-edit model is additive-only, so without
  // this the roadmap only ever grows.
  const compactAfterDays = config.roadmap?.compact_after_days ?? 60;
  const { result: compactedRoadmap, compacted } = compactRoadmap(currentRoadmap, today, { maxAgeDays: compactAfterDays });
  // compactRoadmap only reaches struck-through `###` subsections, but the
  // section the LLM appends to every run is free prose — so the one part of the
  // document that grows without bound was the one part compaction could not
  // touch. compactShippedLog rolls those aged entries up by month.
  const { result: rolledRoadmap, rolled } = compactShippedLog(compactedRoadmap, today, { maxAgeDays: compactAfterDays });
  // Compaction is itself an edit, so freshen the date when it changes anything
  // (applyEditOps only bumps on an LLM content op, which a compaction-only tick
  // has none of — without this the PR would ship trimmed bodies under a stale
  // "Last Updated" date).
  const changedByCompaction = compacted.length > 0 || rolled.length > 0;
  const baseRoadmap = changedByCompaction ? bumpLastUpdated(rolledRoadmap, today) : rolledRoadmap;
  if (compacted.length > 0) {
    console.log(`SECTION-EDIT: compacted ${compacted.length} long-completed subsection(s): ${compacted.join(' | ')}`);
  }
  if (rolled.length > 0) {
    console.log(`SECTION-EDIT: rolled up ${rolled.length} month(s) of the shipped log: ${rolled.join(', ')}`);
  }

  const prompt = buildSectionEditPrompt(baseRoadmap, snapshot, assessment, config.context);
  const rawResponse = await provider.generate(prompt);

  const parsed = parseEditOps(rawResponse);
  if (!parsed.valid) {
    console.error(`SECTION-EDIT: failed to parse LLM response — ${parsed.error}`);
    console.error(`SECTION-EDIT: raw response (first 500 chars): ${(rawResponse || '').slice(0, 500)}`);
    return { roadmap: currentRoadmap, pr: null, safety: { valid: false, errors: [parsed.error] } };
  }

  // Apply ops to the compacted baseline. Compare against the ORIGINAL roadmap
  // below, so a compaction-only run (LLM returned nothing new) still opens a PR.
  const { result: updatedRoadmap, applied, skipped } = applyEditOps(baseRoadmap, parsed.ops, today);
  console.log(`SECTION-EDIT: ${applied.length} ops applied, ${skipped.length} skipped.`);
  for (const op of applied) console.log(`  applied: ${op}`);
  for (const op of skipped) console.warn(`  skipped: ${op}`);

  if (updatedRoadmap === currentRoadmap) {
    console.log('SECTION-EDIT: no changes after applying ops — skipping PR.');
    return { roadmap: updatedRoadmap, pr: existing?.html_url || null, safety: { valid: true, errors: [] } };
  }

  // Defence-in-depth: the section-edit approach is additive-only, so these
  // guards should always pass. Keep them to catch bugs in applyEditOps.
  const safety = validateRoadmap(updatedRoadmap);
  if (!safety.valid) {
    console.error('SAFETY: Roadmap failed validation after applying ops:');
    for (const err of safety.errors) console.error(`  - ${redactErrorForLog(err)}`);
    return { roadmap: updatedRoadmap, pr: null, safety };
  }

  if (dryRun) {
    console.log('DRY RUN — all guards passed, would create PR with updated roadmap.');
    return { roadmap: updatedRoadmap, pr: null, safety };
  }

  const defaultBranch = snapshot.meta?.default_branch || 'main';
  const branchName = isRefresh ? existing.head.ref : `${ROADMAP_BRANCH_PREFIX}${Date.now()}`;

  // Create the branch only when opening a new PR. On refresh we reuse the
  // existing PR's head ref.
  if (!isRefresh) {
    const ref = await gh.request(`/repos/${owner}/${repo}/git/ref/heads/${defaultBranch}`);
    await gh.request(`/repos/${owner}/${repo}/git/refs`, {
      method: 'POST',
      body: { ref: `refs/heads/${branchName}`, sha: ref.object.sha },
    });
  }

  // The blob SHA the PUT needs, plus the branch's current content for the
  // no-op check below. On a refresh both were already read above — that read
  // is now load-bearing (it is the baseline), so reuse it rather than paying a
  // second round-trip. For a new PR the branch was just forked from the
  // default branch, so this reads what we forked.
  let fileSha = branchFileSha;
  let existingContent = isRefresh && branchFileSha !== undefined ? currentRoadmap : null;
  if (existingContent === null) {
    const f = await readRoadmapFromRef(gh, owner, repo, roadmapPath, branchName);
    if (f) {
      fileSha = f.sha;
      existingContent = f.content;
    }
  }

  // No-op short-circuit: if the new output matches what's already on the
  // refresh branch — exactly, or apart from the "Last Updated" date — skip
  // the commit + PR PATCH to avoid spurious churn.
  if (isRefresh && existingContent !== null && isDateOnlyChange(existingContent, updatedRoadmap)) {
    console.log(`Roadmap unchanged from existing PR ${existing.html_url} — skipping refresh push.`);
    return { roadmap: updatedRoadmap, pr: existing.html_url, safety, refreshed: false };
  }

  await gh.request(`/repos/${owner}/${repo}/contents/${roadmapPath}`, {
    method: 'PUT',
    body: {
      message: isRefresh ? 'chore: refresh roadmap update (repo-butler)' : 'chore: update roadmap (repo-butler)',
      content: Buffer.from(updatedRoadmap).toString('base64'),
      branch: branchName,
      ...(fileSha ? { sha: fileSha } : {}),
    },
  });

  // Build the PR body, validating any LLM-supplied assessment text. The
  // assessment text reaches GitHub directly, so it must pass the same safety
  // checks as any other LLM output (blocked URLs, @mentions, API keys, …).
  const { body: prBody, redacted, truncated, errors: bodyErrors } = buildSafePrBody(assessment?.assessment);
  if (truncated && !redacted) {
    console.log(`SAFETY: Assessment truncated to ${6000} chars before validation (verbose but benign).`);
  }
  if (redacted) {
    console.warn('SAFETY: Roadmap PR body assessment failed validation, using safe fallback body:');
    // Redact user-controlled content from each error string before logging
    // (otherwise an @mention or URL host blocked here would just leak into CI logs).
    for (const err of bodyErrors) console.warn(`  - ${redactErrorForLog(err)}`);
  }

  if (isRefresh) {
    // Update the existing PR's body so the Assessment text reflects the
    // current run; the diff itself updates automatically because the head
    // branch moved with the PUT above.
    await gh.request(`/repos/${owner}/${repo}/pulls/${existing.number}`, {
      method: 'PATCH',
      body: { body: prBody },
    });
    console.log(`Refreshed existing roadmap PR ${existing.html_url}`);
    return { roadmap: updatedRoadmap, pr: existing.html_url, safety, refreshed: true };
  }

  const pr = await gh.request(`/repos/${owner}/${repo}/pulls`, {
    method: 'POST',
    body: {
      title: 'chore: update roadmap (repo-butler)',
      head: branchName,
      base: defaultBranch,
      body: prBody,
    },
  });

  console.log(`PR created: ${pr.html_url}`);
  return { roadmap: updatedRoadmap, pr: pr.html_url, safety };
}

// Parse the LLM response as a JSON array of edit operations. Strips markdown
// code fences if present. Exported for testing.
export function parseEditOps(text) {
  if (!text) return { valid: false, error: 'Empty response', ops: [] };
  const stripped = text.replace(/^```(?:json)?\n?/m, '').replace(/\n?```\s*$/m, '').trim();
  try {
    const ops = JSON.parse(stripped);
    if (!Array.isArray(ops)) return { valid: false, error: 'Response is not a JSON array', ops: [] };
    return { valid: true, ops };
  } catch (e) {
    return { valid: false, error: `Invalid JSON: ${e.message}`, ops: [] };
  }
}

// Find the insertion point (character index) for appending to a section.
// Inserts before the next `---` or `## ` boundary after the section heading.
function findSectionInsertPoint(roadmap, sectionName) {
  const bounds = sectionBounds(roadmap, sectionName);
  return bounds ? bounds.end : -1;
}

// Collapse whitespace so a re-emitted paragraph that differs only in wrapping
// still compares equal to the one already on the page.
const normalizeParagraph = (s) => s.trim().replace(/\s+/g, ' ');

// Character bounds of a `## <section>` block's body — from the end of the
// heading line to the next `---` or `## ` boundary. Null when the section is
// absent. The single definition of where a section starts and stops: shared by
// findSectionInsertPoint, applyEditOps' duplicate guard and compactShippedLog,
// so a change to what terminates a section cannot leave the three disagreeing.
// Exported for testing.
export function sectionBounds(roadmap, sectionName) {
  const headingRe = new RegExp(`^## ${sectionName.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\b.*$`, 'm');
  const match = roadmap.match(headingRe);
  if (!match) return null;

  const start = match.index + match[0].length;
  const rest = roadmap.slice(start);
  const boundary = rest.match(/\n(?=---\s*\n|## )/);
  return { start, end: boundary ? start + boundary.index : roadmap.length };
}

// Recover a recurring LLM malformation before classification: the model puts
// the section name directly in the `action` field (e.g.
// {"action":"Implemented","text":"…"}) instead of the documented
// {"action":"append","section":"Implemented","text":"…"}. The live pipeline
// dropped two such ops on 2026-05-29 as "unknown action: Implemented",
// silently losing genuinely-new Implemented entries. When `action` is itself a
// valid section name, reinterpret the op as an append to that section — an
// explicit valid `section` field still wins if present. Genuinely unknown
// actions (e.g. "delete") are returned untouched and still skipped downstream,
// preserving the additive-only guarantee. Exported for testing.
export function normalizeEditOp(op) {
  if (!op || typeof op !== 'object') return op;

  // Canonicalize a section name to its exact SECTION_NAMES casing. LLMs drift
  // ("implemented", "next up"), and findSectionInsertPoint matches the heading
  // case-sensitively — so a drifted-case section would silently fail to insert.
  // Returns undefined when the name is not a known section.
  const canonical = (name) =>
    typeof name === 'string'
      ? SECTION_NAMES.find(s => s.toLowerCase() === name.toLowerCase())
      : undefined;

  // Section-name-in-the-action-field malformation: reinterpret as an append to
  // that section. An explicit valid `section` field still wins if present.
  if (op.action && op.action !== 'append') {
    const fromAction = canonical(op.action);
    if (fromAction) {
      return { ...op, action: 'append', section: canonical(op.section) || fromAction };
    }
  }

  // Well-formed append with a drifted-case section: normalize so the
  // case-sensitive findSectionInsertPoint can locate the heading.
  if (op.action === 'append') {
    const c = canonical(op.section);
    if (c && c !== op.section) return { ...op, section: c };
  }

  return op;
}

// Apply edit operations to the roadmap deterministically. Only additive
// operations are supported — the LLM cannot delete or rewrite content.
// Exported for testing.
export function applyEditOps(roadmap, ops, today) {
  let result = roadmap;
  const applied = [];
  const skipped = [];
  // Refs the roadmap already records as completed work: only refs on lines
  // carrying the shipped convention (~~strikethrough~~ or a "shipped" marker)
  // count. A ref in a live entry (e.g. "Fix X (issue #211)" under Next Up)
  // must not block the append announcing that work shipped — resolved issues
  // reach the prompt as bare issue numbers with no PR number to cite, so a
  // legitimate shipped entry may carry no new ref at all.
  //
  // Deliberately NOT widened to "every ref in the Implemented section". That
  // reading suppressed a Next Up follow-up citing already-shipped PRs, and
  // imported foreign numbering — ROADMAP.md cites `upstream #10940`, which
  // would have silently blocked any entry mentioning that upstream issue.
  // Exact duplicates are caught by identity below instead, where the
  // comparison is scoped to the section actually being written to.
  const shippedRefs = extractIssueRefs(
    roadmap.split('\n').filter(l => /~~|\bshipped\b/i.test(l)).join('\n'),
  );

  for (const rawOp of ops) {
    const op = normalizeEditOp(rawOp);
    if (!op || !op.action) {
      skipped.push('invalid op (missing action)');
      continue;
    }

    if (op.action === 'append') {
      const section = op.section;
      const text = op.text?.trim();
      if (!section || !text) {
        skipped.push(`append: missing section or text`);
        continue;
      }
      const insertAt = findSectionInsertPoint(result, section);
      if (insertAt === -1) {
        skipped.push(`append: section "${section}" not found`);
        continue;
      }
      // Reject an entry the section already carries verbatim. This is the
      // defect the ref check below cannot see: the model re-emits a paragraph
      // it already wrote, and matching on refs misses it whenever the entry
      // carries no #NN ref at all, or its refs never appear on a line using
      // the shipped convention — "reinforced", "completed" and "simplified"
      // account for 22 of ROADMAP.md's 40 entries, and two exact duplicates
      // (#368 and #370–#374) reached the committed file that way.
      // Compared against `result`, not `roadmap`, so a duplicate of an entry
      // appended earlier in this same run is caught too; and scoped to the
      // target section, so the same sentence may legitimately appear under
      // both Next Up and Implemented.
      const bounds = sectionBounds(result, section);
      const sectionParagraphs = bounds
        ? result.slice(bounds.start, bounds.end).split(/\n{2,}/).map(normalizeParagraph)
        : [];
      if (sectionParagraphs.includes(normalizeParagraph(text))) {
        skipped.push(`append: "${section}" already contains this entry verbatim — duplicate`);
        continue;
      }
      // Reject re-summaries: an entry whose every #NN ref is already recorded
      // as shipped adds no new information, despite the prompt forbidding
      // repetition. PR #262 appended a paragraph citing only PRs #239–#241,
      // all covered by existing SHIPPED entries. An entry with at least one
      // new ref (a follow-up citing old work plus a new PR) still applies;
      // ref-less entries can't be judged deterministically and pass through.
      // Ref-list logging is capped at ten, with an overflow count.
      const refs = [...extractIssueRefs(text)];
      if (refs.length > 0 && refs.every(r => shippedRefs.has(r))) {
        const head = refs.slice(0, 10).join(', ');
        const overflow = refs.length > 10 ? ` (and ${refs.length - 10} more)` : '';
        skipped.push(`append: every ref (${head}${overflow}) is already documented as shipped — duplicate entry`);
        continue;
      }
      // Separate the entry from its neighbours with exactly one blank line on
      // each side. The naive `slice + '\n\n' + text + slice` left the text
      // flush against the following `---`, and in CommonMark a paragraph
      // followed directly by `---` is a setext heading underline — so the last
      // entry in a section rendered as a large <h2> and the horizontal rule
      // disappeared. Every roadmap update did this silently from at least #330
      // (it is invisible in a diff, only in the rendered file). Normalising
      // both sides also collapses the stray double blank line the old form
      // left above the entry, and keeps the result stable however the
      // surrounding whitespace happens to be laid out.
      const before = result.slice(0, insertAt).replace(/\s*$/, '');
      const after = result.slice(insertAt).replace(/^\s*/, '');
      result = `${before}\n\n${text}${after ? `\n\n${after}` : '\n'}`;
      applied.push(`append to "${section}" (${text.length} chars)`);
      // An applied entry's refs now count as documented, so a second op in
      // the same response restating the same work is caught intra-run too.
      for (const r of refs) shippedRefs.add(r);
    } else {
      skipped.push(`unknown action: ${op.action}`);
    }
  }

  // Bump the "Last Updated" line only when a content op actually changed the
  // document. An unconditional bump made every daily run produce a PR whose
  // entire diff was this one line — churn, not an update.
  if (result !== roadmap) {
    const dateReplaced = bumpLastUpdated(result, today);
    if (dateReplaced !== result) {
      result = dateReplaced;
      applied.push(`update_date → ${today}`);
    }
  }

  return { result, applied, skipped };
}

// Replace the date on the "**Last Updated:**" line with `today`. No-op when the
// line is absent. Shared by applyEditOps and the compaction path so a
// compaction-only run still freshens the date. Exported for testing.
export function bumpLastUpdated(text, today) {
  return text.replace(/(\*\*Last Updated:\*\*)\s*\d{4}-\d{2}-\d{2}/, `$1 ${today}`);
}

// Whole days from ISO date `aIso` to `bIso` (positive when b is later). Both
// are `YYYY-MM-DD`; parsed at UTC midnight so DST never shifts the count.
function daysBetween(aIso, bIso) {
  const a = new Date(`${aIso}T00:00:00Z`).getTime();
  const b = new Date(`${bIso}T00:00:00Z`).getTime();
  return Math.round((b - a) / 86400000);
}

// Newest `YYYY-MM-DD` in `text`, or null. ISO dates sort lexically as they sort
// chronologically, so the last after a plain sort is the most recent.
function newestDate(text) {
  const dates = (text || '').match(/\d{4}-\d{2}-\d{2}/g) || [];
  return dates.length ? dates.sort().at(-1) : null;
}

// Compact long-completed roadmap subsections so the live document stays well
// under the length ceiling; git history keeps the full prose. A subsection is a
// `### <heading>` block spanning to the next `###`/`## `/`---`/EOF. A block is
// eligible only when its heading is struck through (`~~...~~`, the SHIPPED
// convention), its body is at least `minBodyChars`, and its newest embedded date
// is at least `maxAgeDays` old. The body is then replaced with a one-line pointer
// preserving the newest date, every #NN reference, every markdown link (deduped
// by target, author's text kept), and any bare `docs/decisions/` ADR paths
// (re-linked as `[ADR-NNN](path)`); the heading is left exactly as-is. Active
// (non-struck) blocks, recent completions, and the free-prose
// `## Implemented` section are never touched — this only trims work the project
// finished long ago. Idempotent: a compacted body is recognized by its summary
// shape (it usually also falls below `minBodyChars`, but a ref/link-heavy
// summary need not), so re-running is a no-op. Pure function. Exported for
// testing.
export function compactRoadmap(roadmap, today, { maxAgeDays = 60, minBodyChars = 400 } = {}) {
  if (!roadmap) return { result: roadmap, compacted: [] };
  const lines = roadmap.split('\n');

  // Locate the [headingIdx, end) line span of every `### ` subsection.
  const blocks = [];
  for (let i = 0; i < lines.length; i++) {
    if (/^### /.test(lines[i])) {
      let j = i + 1;
      while (j < lines.length && !/^(### |## |---\s*$)/.test(lines[j])) j++;
      blocks.push({ headingIdx: i, end: j });
      i = j - 1;
    }
  }

  const compacted = [];
  // Splice from the back so earlier line indices stay valid as spans shrink.
  for (const { headingIdx, end } of blocks.reverse()) {
    const heading = lines[headingIdx];
    // The title itself must be struck through (`### ~~...~~`) — the SHIPPED
    // convention for a completed entry. An active heading that merely mentions
    // a struck phrase mid-line (`### Phase 2 (replaces ~~old idea~~)`) is not a
    // completed entry and must not be compacted.
    if (!/^###\s+~~.+~~/.test(heading)) continue;
    const body = lines.slice(headingIdx + 1, end).join('\n');
    const bodyText = body.trim();
    // A summary produced by an earlier pass is already compact — recognize it
    // by shape, not just length: with enough refs + ADR links a summary can
    // exceed minBodyChars, and re-processing it would report a phantom
    // compaction, which bumps **Last Updated** in runUpdate and opens a
    // date-only roadmap PR on every tick. (`.` cannot cross a newline, so a
    // multi-line body never trips this and stays eligible.) `details?` accepts
    // the pre-#312-review "Full detail" wording too: ROADMAP.md still carries
    // summaries minted with the old phrase, and re-compacting them would churn
    // a date-only PR for pure wording.
    if (/^Shipped \d{4}-\d{2}-\d{2}\b.*Full details? in git history\.$/.test(bodyText)) continue;
    if (bodyText.length < minBodyChars) continue;           // already short
    // Consider both body and heading dates (some entries date the heading, e.g.
    // `### ~~Landscape evaluation~~ — EVALUATED 2026-05-28`) and take the newest.
    const newest = newestDate(`${body}\n${heading}`);
    if (!newest) continue;                                  // undatable → leave it
    const age = daysBetween(newest, today);
    // Fail safe: if the age can't be computed (a malformed date token wins the
    // sort, or `today` is invalid), keep the block rather than compact it —
    // NaN comparisons are false, so the "too recent" skip would otherwise miss.
    if (!Number.isFinite(age) || age < maxAgeDays) continue; // undatable or too recent
    const refs = [...extractIssueRefs(body)];
    const refPart = refs.length ? ` (${refs.join(', ')})` : '';
    // Markdown links are the section's pointers into files, research notes and
    // decision records — dropping them costs discoverability (PR #312 review),
    // so carry every one (plus bare ADR paths, re-linked) alongside the PR refs.
    const links = extractSummaryLinks(body);
    const linkPart = links.length ? ` See ${links.join(', ')}.` : '';
    const summary = `Shipped ${newest}${refPart}.${linkPart} Full details in git history.`;
    lines.splice(headingIdx + 1, end - headingIdx - 1, '', summary, '');
    compacted.push(heading.replace(/^###\s+/, '').trim());
  }

  return { result: lines.join('\n'), compacted: compacted.reverse() };
}

// The machine-managed shape a rolled-up month takes. Recognised on the way back
// in, so a later run merges newly-aged entries into the month's existing line
// instead of minting a second line for the same month.
const SHIPPED_ROLLUP_RE = /^\*\*(\d{4}-\d{2})\*\* — (\d+) entr(?:y|ies) \(([^)]*)\)\. Full details in git history\.$/;

// Render a rolled-up month's references, ascending. Listed in full rather than
// collapsed to a first–last span: roadmap prose cites upstream issue numbers
// too (`typescript-eslint` #10940 sits in the 2026-07 entries), and one foreign
// number would turn an honest `#326–#331` into a fabricated `#326–#10940`. A
// full list stays truthful at any length and matches what compactRoadmap
// already writes, at a cost of a few dozen characters per month.
function renderRefList(refs) {
  return [...refs].sort((a, b) => Number(a.slice(1)) - Number(b.slice(1))).join(', ');
}

// Roll up aged entries in the free-prose shipped log so the living document
// keeps recent detail and only a one-line-per-month trace of older work.
//
// This is the companion to compactRoadmap, which only reaches struck-through
// `###` subsections. The section the LLM appends to on every run is free prose,
// so the one part of the document that grew without bound was the one part
// compaction could not touch — which is how ROADMAP.md reached the 60,000-char
// validateRoadmap ceiling on 2026-07-26 with 272 characters to spare.
//
// A paragraph is eligible only when it carries a `YYYY-MM-DD` date at least
// `maxAgeDays` old. Undated paragraphs are passed through untouched, which is
// what keeps the section's evergreen capability description — and any
// hand-written month summary — safe from the roll-up. Each month's first
// eligible paragraph is replaced in place by that month's line, so document
// order is preserved; later paragraphs from the same month are absorbed into
// it. Idempotent: an existing rollup line is parsed back into its bucket and
// re-emitted verbatim when nothing new joined it. Pure function. Exported for
// testing.
//
// This is the ONLY remaining path that removes content from ROADMAP.md, and it
// has no independent preservation check — it relies on by-construction ref
// bucketing to carry every `#NN` into the month line. Three guards used to sit
// on the whole-document rewrite and were deleted with it once `applyEditOps`
// became additive-only: a length check (PR #176 returned 53 lines for 277), a
// strikethrough count (PR #202 stripped 24 `~~…~~` markers), and a ref check
// (PR #213 dropped the paragraph carrying `(PR #84)`). Those failures came
// from an LLM rewriting the document; compaction is deterministic, which is
// why no successor was added. If this ever stops being deterministic — an LLM
// summarising a month rather than concatenating refs — reinstate a ref-
// preservation check first.
export function compactShippedLog(roadmap, today, { maxAgeDays = 60, section = 'Implemented' } = {}) {
  if (!roadmap) return { result: roadmap, rolled: [] };

  const bounds = sectionBounds(roadmap, section);
  if (!bounds) return { result: roadmap, rolled: [] };

  const { start: bodyStart, end: bodyEnd } = bounds;
  const body = roadmap.slice(bodyStart, bodyEnd);

  const paragraphs = body.split(/\n{2,}/);
  const buckets = new Map();   // 'YYYY-MM' → { refs:Set, count, changed, original }
  const output = [];

  for (const para of paragraphs) {
    const text = para.trim();
    if (!text) continue;

    const existing = text.match(SHIPPED_ROLLUP_RE);
    if (existing) {
      const [, month, count, refs] = existing;
      const bucket = buckets.get(month);
      if (bucket) {
        // A second rollup line for a month already seen: fold it in rather than
        // keep both.
        for (const r of extractIssueRefs(refs)) bucket.refs.add(r);
        bucket.count += Number(count);
        bucket.changed = true;
      } else {
        buckets.set(month, { refs: extractIssueRefs(refs), count: Number(count), changed: false, original: text });
        output.push({ rollup: month });
      }
      continue;
    }

    const newest = newestDate(text);
    const age = newest ? daysBetween(newest, today) : NaN;
    // Fail safe: an undatable paragraph, or one whose age cannot be computed,
    // is left exactly as written. NaN comparisons are false, so this also
    // covers a malformed date winning the sort or an invalid `today`.
    if (!Number.isFinite(age) || age < maxAgeDays) {
      output.push({ text });
      continue;
    }

    const month = newest.slice(0, 7);
    const bucket = buckets.get(month);
    if (bucket) {
      for (const r of extractIssueRefs(text)) bucket.refs.add(r);
      bucket.count += 1;
      bucket.changed = true;
    } else {
      buckets.set(month, { refs: extractIssueRefs(text), count: 1, changed: true, original: null });
      output.push({ rollup: month });
    }
  }

  const rolled = [];
  const rendered = output.map(entry => {
    if (!entry.rollup) return entry.text;
    const bucket = buckets.get(entry.rollup);
    // Nothing new joined an already-rolled month — re-emit its line byte for
    // byte, so a quiet tick produces no diff and therefore no roadmap PR.
    if (!bucket.changed) return bucket.original;
    rolled.push(entry.rollup);
    const refPart = renderRefList(bucket.refs);
    const entries = `${bucket.count} ${bucket.count === 1 ? 'entry' : 'entries'}`;
    return `**${entry.rollup}** — ${entries} (${refPart}). Full details in git history.`;
  });

  if (rolled.length === 0) return { result: roadmap, rolled: [] };

  const newBody = `\n\n${rendered.join('\n\n')}\n`;
  return { result: roadmap.slice(0, bodyStart) + newBody + roadmap.slice(bodyEnd), rolled: rolled.sort() };
}

export function buildSectionEditPrompt(currentRoadmap, snapshot, assessment, projectContext, now = new Date()) {
  const today = now.toISOString().slice(0, 10);
  const items = [
    `Today: ${today}`,
    `Repository: ${snapshot.repository}`,
    `Current version: ${snapshot.package?.version || snapshot.summary.latest_release || 'unknown'}`,
    `Open issues: ${snapshot.summary.open_issues}`,
    `Blocked: ${snapshot.summary.blocked_issues}`,
    `Awaiting feedback: ${snapshot.summary.awaiting_feedback}`,
    `PRs merged (90d): ${snapshot.summary.recently_merged_prs}`,
    '',
  ];

  if (assessment?.assessment) {
    items.push('Recent assessment:', sanitizeForPrompt(assessment.assessment), '');
  }

  if (assessment?.diff?.new_issues?.length > 0) {
    items.push('New issues since last update:');
    for (const i of assessment.diff.new_issues.slice(0, 15)) {
      items.push(`  #${i.number}: ${sanitizeForPrompt(i.title)} [${i.labels.join(', ')}]`);
    }
    items.push('');
  }

  if (assessment?.diff?.resolved_issues?.length > 0) {
    items.push('Resolved issues:');
    for (const i of assessment.diff.resolved_issues.slice(0, 15)) {
      items.push(`  #${i.number}: ${sanitizeForPrompt(i.title)}`);
    }
    items.push('');
  }

  // Merged PR titles — the one input this prompt asked the model to reason
  // about but never supplied. The instructions below say "only create entries
  // for genuinely new work visible in the data above (new merged PRs, …)"
  // while the data above carried only a 90-day merged *count*, so the shipped
  // log therefore depended on the assessment prose happening to name the work,
  // rather than on the merge record itself. ASSESS already computes this array
  // (`newMergedPRs` in assess.js); it was simply never read. Same sanitiser and
  // same 15-item cap as the issue blocks above.
  //
  // This is NOT the cause of the entries missing from #353 — that was a
  // separate defect in the refresh path, which rebuilds from the default
  // branch and overwrites the open PR, so each tick destroyed the previous
  // tick's entry. The commit history of #353 shows one correct entry written
  // per tick (#354, then #355, then #356, then #357/#358), each replacing the
  // last. This change removes a different fragility: an instruction that asked
  // the model to reason about merged PRs it was never shown.
  if (assessment?.diff?.new_merged_prs?.length > 0) {
    items.push('PRs merged since last update:');
    for (const p of assessment.diff.new_merged_prs.slice(0, 15)) {
      items.push(`  #${p.number}: ${sanitizeForPrompt(p.title)}`);
    }
    items.push('');
  }

  if (assessment?.diff?.new_releases?.length > 0) {
    items.push('New releases:');
    for (const r of assessment.diff.new_releases) {
      items.push(`  ${r.tag} (${r.published_at?.split('T')[0]})`);
    }
    items.push('');
  }

  items.push('High-reaction issues:', ...(snapshot.summary.high_reaction_issues.map(i => `  ${sanitizeForPrompt(i)}`)), '');
  items.push('Top labels:', ...(snapshot.summary.top_open_labels.map(l => `  ${l}`)), '');

  if (currentRoadmap) {
    items.push('--- CURRENT ROADMAP (read-only context, do NOT reproduce) ---', sanitizeForPrompt(currentRoadmap), '--- END CURRENT ROADMAP ---', '');
  }

  return wrapPrompt({
    role: 'You decide what NEW entries to append to a project roadmap. You do NOT reproduce or edit the existing document — the code handles that. You only output a JSON array of operations.',
    projectContext,
    items,
    outroLines: [
      'Instructions:',
      `- Output a JSON array of append operations. Each operation: {"action": "append", "section": "<name>", "text": "<paragraph>"}`,
      '- The "action" field is ALWAYS the literal string "append". The section name goes in the "section" field, never in "action".',
      `  Wrong: {"action": "Implemented", "text": "…"}`,
      `  Correct: {"action": "append", "section": "Implemented", "text": "…"}`,
      `- Valid section names (for the "section" field): ${SECTION_NAMES.map(s => `"${s}"`).join(', ')}. No other section names are accepted.`,
      '- Only create entries for genuinely new work visible in the data above (new merged PRs, resolved issues, new releases).',
      // Placeholders, not real numbers: the rule two lines below forbids citing
      // PR numbers absent from the data, and a concrete example is the easiest
      // thing for a model to echo straight into an entry. The sibling example
      // below already uses "#N" for the same reason.
      '- Group by capability, not by pull request. Several PRs delivering one capability are ONE entry citing all their numbers (e.g. "(PRs #N, #M)"); one PR delivering nothing user-visible — a dependency bump, a lint fix, a typo, a revert — gets no entry at all. This log is a record of what the project can now do, not a changelog.',
      '- Do not repeat or summarise anything already in the roadmap. Read the current roadmap carefully before deciding.',
      '- If nothing meaningful changed since the last update, return an empty array: []',
      '- Each "text" value should be a single markdown paragraph in the style of existing entries (e.g. "Feature X shipped 2026-05-26 (PR #N). Description of what changed.").',
      '- Do not invent PR numbers, issue numbers, or dates not present in the data above.',
      '- Output ONLY the JSON array, no commentary, no markdown fences, no explanation.',
    ],
  });
}
